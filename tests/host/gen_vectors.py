def gen_fragments(root: Path) -> Header:
    fx = load(root, "fragments.json")
    h = Header("v_fragments")
    h.body.append(f"#define V_FRAG_PAYLOAD {fx['fragment_payload']}u")
    h.body.append("struct v_frag {\n\tconst char *name;\n\tuint16_t max_message;\n\tuint8_t seq_start;\n"
                  "\tuint8_t seq_next;\n\tconst uint8_t *msg;\n\tsize_t msg_len;\n"
                  "\tconst uint8_t *const *frags;\n\tconst size_t *frag_lens;\n\tsize_t n_frags;\n"
                  "\tsize_t error_at;\n};")

    def frags(values: list[str]) -> tuple[str, str]:
        blobs = [h.hexblob(f) for f in values]
        fid, lid = h.ident(), h.ident()
        h.body.append(f"static const uint8_t *const {fid}[] = {{{', '.join(b for b, _ in blobs)}}};")
        h.body.append(f"static const size_t {lid}[] = {{{', '.join(f'{n}u' for _, n in blobs)}}};")
        return fid, lid

    rows = []
    for v in fx["vectors"]:
        msg, n = h.hexblob(v["message"])
        fid, lid = frags(v["fragments"])
        rows.append(f"\t{{{c_str(v['name'])}, {v['max_message']}u, {v['seq_start']}u, {v['seq_next']}u, "
                    f"{msg}, {n}u, {fid}, {lid}, {len(v['fragments'])}u, 0u}},")
    h.body += ["static const struct v_frag v_frag[] = {", *rows, "};"]
    rows = []
    for v in fx["errors"]:
        fid, lid = frags(v["fragments"])
        rows.append(f"\t{{{c_str(v['name'])}, {v['max_message']}u, 0u, 0u, NULL, 0u, {fid}, {lid}, "
                    f"{len(v['fragments'])}u, {v['error_at']}u}},")
    h.body += ["static const struct v_frag v_frag_errors[] = {", *rows, "};"]
    return h


def gen_tag_txn(root: Path) -> Header:
    fx = load(root, "tag_txn.json")
    h = Header("v_tag_txn", ("ctag/proto_ids.h",))
    h.body += [
        f"#define V_TXN_PANEL_PLANES {fx['panel']['planes']}u",
        f"#define V_TXN_PANEL_PLANE_LEN {fx['panel']['plane_len']}u",
        "struct v_txn_rec {\n\tbool present;\n\tuint32_t tag_id;\n\tuint32_t epoch;\n\tuint32_t revision;\n"
        "\tuint64_t update_id;\n\tconst uint8_t *digest;\n\tint status;\n\tint state;\n};",
    ]

    def rec(r: dict[str, Any] | None) -> str:
        if r is None:
            return "{false, 0u, 0u, 0u, 0u, NULL, 0, 0}"
        dig, _ = h.hexblob(r["digest"])
        state = {"DISPLAYED": 0, "REFRESH_INTENT": 1}[r["state"]]
        return (f"{{true, {r['tag_id']}u, {r['epoch']}u, {r['revision']}u, {r['update_id']}u, {dig}, "
                f"{status(r['status_name'])}, {state}}}")

    h.body.append("struct v_txn_frame_begin {\n\tconst char *name;\n\tstruct v_txn_rec stored;\n"
                  "\tuint32_t epoch;\n\tuint32_t revision;\n\tconst uint8_t *digest;\n\tuint8_t planes;\n"
                  "\tuint16_t plane_len;\n\tbool accept;\n\tbool duplicate;\n\tint status;\n};")
    rows = []
    for v in fx["frame_begin"]:
        f, e = v["frame"], v["expect"]
        dig, _ = h.hexblob(f["digest"])
        rows.append(f"\t{{{c_str(v['name'])}, {rec(v['stored'])}, {f['epoch']}u, {f['revision']}u, {dig}, "
                    f"{f['planes']}u, {f['plane_len']}u, {str(e['accept']).lower()}, "
                    f"{str(e['duplicate']).lower()}, {status(e['status_name'])}}},")
    h.body += ["static const struct v_txn_frame_begin v_txn_frame_begin[] = {", *rows, "};"]
    h.body.append("struct v_txn_boot {\n\tconst char *name;\n\tstruct v_txn_rec stored;\n"
                  "\tstruct v_txn_rec expect;\n\tbool persist;\n\tbool flag;\n};")
    rows = []
    for v in fx["boot"]:
        e = v["expect"]
        rows.append(f"\t{{{c_str(v['name'])}, {rec(v['stored'])}, {rec(e['record'])}, "
                    f"{str(e['persist']).lower()}, {str(e['challenge_flag_bit0']).lower()}}},")
    h.body += ["static const struct v_txn_boot v_txn_boot[] = {", *rows, "};"]
    return h


def gen_enrollment(root: Path) -> Header:
    fx = load(root, "enrollment.json")
    h = Header("v_enrollment", ("ctag/proto_ids.h",))
    f = fx["fields"]
    blob, n = h.hexblob(fx["blob"])
    secret, _ = h.hexblob(f["secret"])
    h.body += [
        f"#define V_ENROLL_BLOB {blob}",
        f"#define V_ENROLL_BLOB_LEN {n}u",
        f"#define V_ENROLL_MAGIC 0x{f['magic']:08x}u",
        f"#define V_ENROLL_VERSION {f['version']}u",
        f"#define V_ENROLL_BOARD {f['board']}u",
        f"#define V_ENROLL_PANEL {f['panel']}u",
        f"#define V_ENROLL_FLAGS {f['flags']}u",
        f"#define V_ENROLL_TAG_ID {f['tag_id']}u",
        f"#define V_ENROLL_SECRET {secret}",
        f"#define V_ENROLL_CRC32 0x{f['crc32']:08x}u",
        "struct v_enroll_invalid {\n\tconst char *name;\n\tconst uint8_t *blob;\n\tsize_t len;\n\tint status;\n};",
    ]
    rows = []
    for v in fx["invalid"]:
        b, bn = h.hexblob(v["blob"])
        rows.append(f"\t{{{c_str(v['name'])}, {b}, {bn}u, {status(v['status_name'])}}},")
    h.body += ["static const struct v_enroll_invalid v_enroll_invalid[] = {", *rows, "};"]
    return h


def gen_session(root: Path) -> Header:
    fx = load(root, "session.json")
    h = Header("v_session", ("ctag/proto_ids.h",))
    for key in ("tag_secret", "nonce_b", "nonce_t", "caps", "hello", "challenge", "k_epoch", "th", "mac_b",
                "mac_t", "auth", "auth_ok", "k_b2t", "k_t2b"):
        ident, n = h.hexblob(fx[key])
        h.body += [f"#define V_SESSION_{key.upper()} {ident}", f"#define V_SESSION_{key.upper()}_LEN {n}u"]
    relayed = fx["caps_relayed"]
    for key in ("caps", "th", "auth"):
        ident, n = h.hexblob(relayed[key])
        h.body += [f"#define V_SESSION_RELAYED_{key.upper()} {ident}",
                   f"#define V_SESSION_RELAYED_{key.upper()}_LEN {n}u"]
    assert relayed["status_name"] == "AUTH_FAILED"
    stale = fx["stale_epoch"]
    ident, n = h.hexblob(stale["error"])
    h.body += [f"#define V_SESSION_STALE_STORED_EPOCH {stale['stored_epoch']}u",
               f"#define V_SESSION_STALE_ERROR {ident}", f"#define V_SESSION_STALE_ERROR_LEN {n}u",
               f"#define V_SESSION_STALE_STATUS {status(stale['status_name'])}"]
    nxt, _ = h.hexblob(fx["k_epoch_next"]["k_epoch"])
    bad, _ = h.hexblob(fx["bad_mac_b"]["mac_b"])
    ex = fx["nonce_example"]
    nonce, _ = h.hexblob(ex["nonce"])
    h.body += [
        f"#define V_SESSION_TAG_ID {fx['tag_id']}u",
        f"#define V_SESSION_EPOCH {fx['epoch']}u",
        f"#define V_SESSION_NEXT_EPOCH {fx['k_epoch_next']['epoch']}u",
        f"#define V_SESSION_K_EPOCH_NEXT {nxt}",
        f"#define V_SESSION_BAD_MAC_B {bad}",
        f"#define V_SESSION_NONCE_DIR CTAG_REC_DIR_{ex['direction']}",
        f"#define V_SESSION_NONCE_COUNTER {ex['counter']}u",
        f"#define V_SESSION_NONCE {nonce}",
        "struct v_record {\n\tconst char *name;\n\tint dir; /* enum ctag_rec_dir */\n\tuint32_t counter;\n"
        "\tuint8_t type;\n\tconst uint8_t *plaintext;\n\tsize_t pt_len;\n\tconst uint8_t *record;\n"
        "\tsize_t len;\n};",
    ]
    rows = []
    for r in fx["records"]:
        pt, pn = h.hexblob(r["plaintext"])
        rc, rn = h.hexblob(r["record"])
        rows.append(f"\t{{{c_str(r['type_name'])}, CTAG_REC_DIR_{r['direction']}, {r['counter']}u, "
                    f"{r['type']}u, {pt}, {pn}u, {rc}, {rn}u}},")
    h.body += ["static const struct v_record v_session_records[] = {", *rows, "};"]
    rows = []
    for r in fx["tampered"]:
        rc, rn = h.hexblob(r["record"])
        rows.append(f"\t{{{c_str(r['name'])}, CTAG_REC_DIR_{r['direction']}, {r['expected_counter']}u, 0u, "
                    f"NULL, 0u, {rc}, {rn}u}},")
    h.body += ["static const struct v_record v_session_tampered[] = {", *rows, "};"]
    return h


